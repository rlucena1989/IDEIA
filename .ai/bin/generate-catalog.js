#!/usr/bin/env node
'use strict'
const fs = require('fs')
const path = require('path')
const { ROOT, info, printHelp, parseArgs, writeTextIdempotent, readTextSafe } = require('./lib/common')

const args = parseArgs(process.argv.slice(2))
if (args.help) {
  printHelp('generate-catalog.js', 'node .ai/bin/generate-catalog.js [--backstage] [--json]', [
    '--backstage   Generate Backstage catalog-info.yaml',
    '--json        Output catalog as JSON',
    '--help         Show this help'
  ])
  process.exit(0)
}

const modulesDir = path.join(ROOT, 'src/modules')
const modules = fs.existsSync(modulesDir)
  ? fs.readdirSync(modulesDir).filter(f => fs.statSync(path.join(modulesDir, f)).isDirectory())
  : []

const catalog = {
  project: (readTextSafe(path.join(ROOT, '.ai/project-manifest.yaml')) || '').substring(0, 600),
  modules: modules.map(m => {
    const base = path.join(modulesDir, m)
    const hasDomain = fs.existsSync(path.join(base, 'domain'))
    const hasApp = fs.existsSync(path.join(base, 'application'))
    const hasInfra = fs.existsSync(path.join(base, 'infrastructure'))
    const hasPresentation = fs.existsSync(path.join(base, 'presentation'))
    const layers = []
    if (hasDomain) layers.push('domain')
    if (hasApp) layers.push('application')
    if (hasInfra) layers.push('infrastructure')
    if (hasPresentation) layers.push('presentation')
    const entityDir = path.join(base, 'domain/entities')
    const entities = fs.existsSync(entityDir)
      ? fs.readdirSync(entityDir).filter(f => f.endsWith('.ts')).map(f => f.replace('.ts', ''))
      : []
    const ucDir = path.join(base, 'application/usecases')
    const usecases = fs.existsSync(ucDir)
      ? fs.readdirSync(ucDir).filter(f => f.endsWith('.ts') && !f.endsWith('.spec.ts')).map(f => f.replace('UseCase.ts', '').replace('.ts', ''))
      : []
    return { name: m, layers, entities, useCases: usecases }
  }),
  timestamp: new Date().toISOString()
}

if (args.json) {
  console.log(JSON.stringify(catalog, null, 2))
  process.exit(0)
}

if (args.backstage) {
  const bsYaml = [
    'apiVersion: backstage.io/v1alpha1',
    'kind: Component',
    'metadata:',
    "  name: '" + ((readTextSafe(path.join(ROOT, 'ai-devkit.config.json')) || '{}').projectName || 'app') + "'",
    "  description: 'Generated by ai-devkit'",
    'spec:',
    '  type: service',
    '  lifecycle: experimental',
    '  owner: team-dev',
    '  system: ' + (modules.length > 0 ? 'modular-monolith' : 'backend'),
  ]
  writeTextIdempotent(path.join(ROOT, 'catalog-info.yaml'), bsYaml.join('\n'))
  info('Backstage catalog-info.yaml generated')
}

const lines = [
  '# Technical Catalog',
  '',
  'Generated: ' + new Date().toISOString(),
  'Modules discovered: ' + modules.length,
  ''
]

if (modules.length === 0) {
  lines.push('_No modules found in src/modules/._')
} else {
  for (const m of catalog.modules) {
    lines.push('## ' + m.name)
    lines.push('')
    lines.push('| Property | Value |')
    lines.push('|----------|-------|')
    lines.push('| Layers | ' + (m.layers.length > 0 ? m.layers.join(', ') : 'none') + ' |')
    lines.push('| Entities | ' + (m.entities.length > 0 ? m.entities.join(', ') : 'none') + ' |')
    lines.push('| Use Cases | ' + (m.useCases.length > 0 ? m.useCases.join(', ') : 'none') + ' |')
    lines.push('')
  }
}

const catalogYaml = [
  'modules:'
]
for (const m of catalog.modules) {
  catalogYaml.push('  - name: ' + m.name)
  catalogYaml.push('    description: Auto-discovered module')
  catalogYaml.push('    owner: team-dev')
}
catalogYaml.push('')
writeTextIdempotent(path.join(ROOT, '.ai/catalog/modules.yaml'), catalogYaml.join('\n'))

writeTextIdempotent(path.join(ROOT, '.ai/docs/catalog.md'), lines.join('\n'))
info('Catalog generated: ' + modules.length + ' module(s) discovered in src/modules/')